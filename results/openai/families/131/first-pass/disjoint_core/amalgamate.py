#!/usr/bin/env python3
"""Assemble the pinned disjoint proof closure without evaluating upstream Lake."""

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "upstream" / "lean"
TARGETS = (
    "OAI.Probability.SwitchChain.PairDisjointAssembly",
    "OAI.Probability.SwitchChain.PairActualAffine",
    "OAI.Probability.SwitchChain.PairEqualityBudgetUnordered",
)
IMPORT = re.compile(r"^(?:public )?import\s+(\S+)\s*$")
RENAMES = {
    "dite_eq_left": "dif_pos",
    "dite_eq_right": "dif_neg",
    "ite_eq_left": "if_pos",
    "ite_eq_right": "if_neg",
}

EXTENSION = r"""
namespace Argus9000131

open OAI.Problem315
open OAI.Problem315.PairResampling
open scoped BigOperators
set_option maxHeartbeats 1000000

noncomputable def disjointForm {n : ℕ} {d : Fin n → ℕ}
    (f g : StateSpace n d) : ℝ := by
  classical
  exact ∑ a ∈ PairResampling.pairs n, ∑ b ∈ PairResampling.pairs n,
    if Disjoint a b then
      inner ℝ (PairResampling.fluctuation n d a f) (PairResampling.fluctuation n d b g)
    else 0

theorem disjoint_form_symmetric {n : ℕ} {d : Fin n → ℕ}
    (f g : StateSpace n d) :
    disjointForm f g = disjointForm g f := by
  classical
  unfold disjointForm
  rw [Finset.sum_comm]
  apply Finset.sum_congr rfl
  intro a ha
  apply Finset.sum_congr rfl
  intro b hb
  by_cases hab : Disjoint a b
  · simp only [if_pos hab, if_pos hab.symm]
    exact real_inner_comm _ _
  · have hba : ¬ Disjoint b a := fun h => hab h.symm
    simp only [if_neg hab, if_neg hba]

theorem disjoint_core_nonnegative {n : ℕ} {d : Fin n → ℕ}
    (f : StateSpace n d) : 0 ≤ disjointForm f f := by
  exact PairResampling.disjoint_sum_nonneg_of_named_interaction_budget f
    (fun i j k l h => PairEquality.actual_named_interaction i j k l h f)
    (fun a _ => PairEquality.pair_projection_budget a f)

theorem disjoint_core {n : ℕ} {d : Fin n → ℕ}
    (f g : StateSpace n d) :
    disjointForm f g = disjointForm g f ∧ 0 ≤ disjointForm f f :=
  ⟨disjoint_form_symmetric f g, disjoint_core_nonnegative f⟩

theorem sharp_interaction_identity (m : ℝ) (hm : 0 < m) :
    -2 * m^2 / ((m+1) * (m+2)^2) =
      -(m/(m+2)) * (2*m/((m+1)*(m+2))) := by
  have h1 : m+1 ≠ 0 := by linarith
  have h2 : m+2 ≠ 0 := by linarith
  field_simp
  <;> ring

theorem sharp_ratio_lt_one (m : ℝ) (hm : 0 < m) :
    0 < m/(m+2) ∧ m/(m+2) < 1 := by
  have hp : 0 < m+2 := by linarith
  exact ⟨div_pos hm hp, (div_lt_one hp).2 (by linarith)⟩

theorem no_uniform_smaller_ratio (c : ℝ) (hc : c < 1) :
    ∃ m : ℕ, 0 < m ∧ c < (m:ℝ)/((m:ℝ)+2) := by
  obtain ⟨m, hm⟩ := exists_nat_gt (max (0:ℝ) (2*c/(1-c)))
  have hpos : (0:ℝ) < m := lt_of_le_of_lt (le_max_left _ _) hm
  have hbound : 2*c/(1-c) < (m:ℝ) :=
    lt_of_le_of_lt (le_max_right _ _) hm
  have hden : 0 < 1-c := by linarith
  have hprod := (div_lt_iff₀ hden).1 hbound
  refine ⟨m, by exact_mod_cast hpos, ?_⟩
  apply (lt_div_iff₀ (by linarith : 0 < (m:ℝ)+2)).2
  nlinarith

#print axioms disjoint_core
#print axioms PairEquality.actual_named_interaction
#print axioms PairEquality.pair_projection_budget
#print axioms SliceNormalized.projection_comparison
#print axioms no_uniform_smaller_ratio

end Argus9000131
"""


def main():
    ordered = []
    active = set()
    done = set()

    def visit(module):
        if module in done:
            return
        if module in active:
            raise ValueError(f"cyclic upstream imports at {module}")
        active.add(module)
        path = SOURCE.joinpath(*module.split(".")).with_suffix(".lean")
        text = path.read_text()
        for line in text.splitlines():
            match = IMPORT.fullmatch(line)
            if match:
                imported = match.group(1)
                if imported.startswith("OAI."):
                    visit(imported)
                elif imported != "Mathlib" and not imported.startswith("Mathlib."):
                    raise ValueError(f"uninspected external import {imported}")
        active.remove(module)
        done.add(module)
        ordered.append((module, text))

    for target in TARGETS:
        visit(target)
    pieces = [
        "/- Disjoint-core reproduction from openai/math under Apache-2.0,\n"
        "commit 4eaee87548250b2682affda7d05d947c05554bae.\n"
        "Changed: amalgamated imports, Lean 4.31 conditional-lemma names,\n"
        "the older ReflTransGen.lift argument convention, and an explicit\n"
        "definitional Finset.mapEmbedding reduction.\n"
        "Generated by amalgamate.py; upstream Lake is not evaluated.\n"
        "See LICENSE.upstream for the original license. -/\n",
        "import Mathlib\nset_option maxErrors 200\n",
    ]
    for module, text in ordered:
        pieces.append(f"\n/- BEGIN PINNED MODULE {module} -/\n")
        for old, new in RENAMES.items():
            text = re.sub(r"\b" + old + r"\b", new, text)
        text = text.replace(
            "Relation.ReflTransGen.lift (fun K : A => K.val) (fun _ _ h => h) _ _ hpath",
            "Relation.ReflTransGen.lift (fun K : A => K.val) (fun _ _ h => h) hpath",
        )
        text = text.replace(
            "simp [average, Finset.powersetCard_map]",
            "simp [average, Finset.powersetCard_map] <;> rfl",
        )
        pieces.extend(
            line + "\n"
            for line in text.splitlines()
            if not IMPORT.fullmatch(line)
        )
        pieces.append(f"/- END PINNED MODULE {module} -/\n")
    pieces.append(EXTENSION)
    destination = ROOT / "Main.lean"
    destination.write_text("".join(pieces))
    print(f"Assembled {len(ordered)} pinned modules into {destination.name}")


if __name__ == "__main__":
    main()
